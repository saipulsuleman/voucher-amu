-- 1. Table Customers (Instansi / Pelanggan)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Table Transactions (Header Nota Kupon & Kwitansi)
CREATE TABLE IF NOT EXISTS public.transactions (
    id TEXT PRIMARY KEY,
    nota_number TEXT NOT NULL,
    transaction_date DATE NOT NULL,
    customer_name TEXT NOT NULL,
    officer_name TEXT NOT NULL,
    total_sheets INTEGER NOT NULL,
    voucher_subtotal NUMERIC NOT NULL,
    admin_fee NUMERIC NOT NULL,
    clearing_fee NUMERIC DEFAULT 0,
    grand_total NUMERIC NOT NULL,
    terbilang TEXT NOT NULL,
    payment_voucher TEXT DEFAULT 'Tunai' NOT NULL,
    payment_admin TEXT DEFAULT 'Tunai' NOT NULL,
    status TEXT DEFAULT 'SUKSES' NOT NULL,
    void_reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Table Transaction Items (Rincian Pecahan Per Baris)
CREATE TABLE IF NOT EXISTS public.transaction_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id TEXT REFERENCES public.transactions(id) ON DELETE CASCADE,
    voucher_code TEXT NOT NULL,
    serial_start TEXT NOT NULL,
    serial_end TEXT NOT NULL,
    quantity INTEGER NOT NULL,
    item_subtotal NUMERIC NOT NULL,
    admin_subtotal NUMERIC NOT NULL,
    custom_price NUMERIC DEFAULT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(transaction_id, voucher_code, serial_start)
);

-- Enable Row Level Security (RLS) & Public Access Policies
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transaction_items ENABLE ROW LEVEL SECURITY;

